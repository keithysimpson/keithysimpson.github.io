#!/usr/bin/env python3
"""
Extract the layers of a dressing-up PSD into a folder the HTML app can read.

    pip install psd-tools pillow
    python3 extract_psd.py path/to/file.psd            # writes into this script's folder
    python3 extract_psd.py file.psd --out some/folder

Layer rules (PSD layer panel, bottom to top):
  * the BOTTOM layer is the body/base - it stays fixed on screen
  * every other layer is a clothing item
  * stacking order in the PSD = stacking order on the body (trousers above socks etc.)
  * hidden layers are skipped; a group counts as one item

Output:
  images/<layer name>.png   each layer, trimmed, transparent background
  items.js                  positions + stacking order + where each item waits

Re-running keeps any "home" positions you have hand-edited in items.js
(matched by layer name), so you can tweak the layout without losing it.
"""
import argparse, json, os, re, sys

try:
    from psd_tools import PSDImage
except ImportError:
    sys.exit("Missing dependency. Run:  pip install psd-tools pillow")

SIDE = 278            # empty space either side of the body for the item panels
HOME_SCALE = 0.7      # size of items while they wait at the side
COL_W = 340           # max width an item may take at the side (after scaling)


def slug(name):
    s = re.sub(r"[^A-Za-z0-9_-]+", "_", name.replace("\x00", "").strip()).strip("_")
    return s or "layer"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("psd")
    ap.add_argument("--out", default=os.path.dirname(os.path.abspath(__file__)))
    a = ap.parse_args()

    psd = PSDImage.open(a.psd)
    layers = [l for l in psd if l.visible]
    if len(layers) < 2:
        sys.exit("Need at least a base layer plus one clothing layer.")

    img_dir = os.path.join(a.out, "images")
    os.makedirs(img_dir, exist_ok=True)

    # keep previously hand-edited home positions
    cfg_path = os.path.join(a.out, "items.js")
    old_home = {}
    if os.path.exists(cfg_path):
        try:
            txt = open(cfg_path, encoding="utf-8").read()
            old = json.loads(txt[txt.index("{"): txt.rindex("}") + 1])
            old_home = {i["name"]: i for i in old["items"] if "home" in i}
        except Exception:
            pass

    items, seen = [], set()
    for z, l in enumerate(layers):
        name = slug(l.name)
        while name in seen:
            name += "_2"
        seen.add(name)
        im = l.composite()
        if im is None:
            print(f"skipping empty layer {name}")
            continue
        im = im.convert("RGBA")
        bbox = im.getchannel("A").getbbox()          # trim transparent margins
        if bbox is None:
            print(f"skipping empty layer {name}")
            continue
        im = im.crop(bbox)
        im.save(os.path.join(img_dir, name + ".png"))
        items.append(dict(name=name, file=f"images/{name}.png", z=z,
                          x=l.left + bbox[0], y=l.top + bbox[1], w=im.width, h=im.height))
        print(f"{z}: {name}  {im.width}x{im.height}")

    base, clothes = items[0], items[1:]
    stage_w, stage_h = psd.width + 2 * SIDE, psd.height

    # auto-layout: alternate left / right panels, spread evenly down the height
    cols = {0: [], 1: []}
    for i, it in enumerate(clothes):
        cols[i % 2].append(it)
    for c, group in cols.items():
        cx = 215 if c == 0 else stage_w - 215      # centre of the 390px-wide side panels
        slot = (stage_h - 300) / max(len(group), 1)
        for k, it in enumerate(group):
            it["homeScale"] = round(min(HOME_SCALE, COL_W / it["w"], (slot - 20) / it["h"]), 3)
            it["home"] = [round(cx), round(150 + slot * (k + 0.5))]
    for it in clothes:
        if it["name"] in old_home:
            it["home"] = old_home[it["name"]]["home"]
            it["homeScale"] = old_home[it["name"]].get("homeScale", it["homeScale"])

    cfg = dict(stage=[stage_w, stage_h], offsetX=SIDE, snapDistance=230,
               base=base, items=clothes)
    with open(cfg_path, "w", encoding="utf-8") as f:
        f.write("// Generated by extract_psd.py. 'home' = [x, y] of the item's centre while it waits.\n")
        f.write("window.DRESS_CONFIG = " + json.dumps(cfg, indent=1) + ";\n")
    print(f"\nWrote {len(items)} images and items.js to {a.out}")


if __name__ == "__main__":
    main()
